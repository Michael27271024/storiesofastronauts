enum class BossAttackPattern {
    ORB_VOLLEY,
    SHOCK_RING,
    METEOR_STRIKE,
    SWEEP_BEAM,
    SPIRAL_BARRAGE
}

data class Boss3DSpec(
    val stageNumber: Int,
    val chapterIndex: Int,
    val codename: String,
    val titleFa: String,
    val titleEn: String,
    val titleAr: String,
    val introLineFa: String,
    val introLineEn: String,
    val phaseCount: Int,
    val baseHp: Int,
    val bossScale: Float,
    val arenaRadius: Float,
    val satelliteCount: Int,
    val coverPillarCount: Int,
    val hasOrbitalRings: Boolean,
    val hasDualWingCannons: Boolean,
    val isDarkEclipse: Boolean,
    val isGrandFinale: Boolean,
    val skyTopColor: FloatArray,
    val skyBottomColor: FloatArray,
    val deckColor: FloatArray,
    val deckTrimColor: FloatArray,
    val planetColor: FloatArray,
    val planetRingColor: FloatArray?,
    val hullColor: FloatArray,
    val coreGlowColor: FloatArray,
    val hazardColor: FloatArray,
    val attackIntervalSec: Float,
    val bossMoveSpeed: Float,
    val allowedPatterns: List<BossAttackPattern>
) {
    fun localizedTitle(langCode: String): String = when (langCode) {
        "en" -> titleEn
        "ar" -> titleAr
        else -> titleFa
    }

    fun localizedIntro(langCode: String): String = when (langCode) {
        "en" -> introLineEn
        else -> introLineFa
    }
}

